"use client";

import { useState } from "react";
import { formatReleaseTime, parseReleaseTime } from "../lib/timeInput";
import {
  SPEED_INPUT_PATTERN,
  formatSpeed,
  parseSpeedInput,
} from "../lib/measurement/speedInput";
import type { ResolvedBlockMeasurement } from "../lib/measurement/quantities";
import { toleranceBandLabel } from "../lib/measurement/tolerance";
import type { Handle, ShotType } from "../types";
import { surfaceClass } from "./Surface";

export type ShotEntryTarget = {
  value: number;
  editable: boolean;
  autoGenerated: boolean;
};

/**
 * One stone's worth of entry, as gathered by whichever control captured it.
 *
 * Structured rather than positional because a stone may legitimately carry a time, a
 * speed, or both, and an absent measurement must be genuinely absent — a positional
 * `releaseTime: number` could only express "missing" as a fabricated number. Both
 * entry controls (this one and BlindShotEntry) submit through this one shape, so
 * there stays exactly one path that appends a stone.
 */
export type AddShotInput = {
  releaseTime?: number;
  speed?: number;
  handle: Handle;
  shotType?: ShotType;
  targetTimeOverride?: number;
  predictedTime?: number;
  /**
   * True when this stone came from the parent-owned manual draft, whose REVISION is
   * what makes a repeated press of the same unedited draft idempotent.
   *
   * A control that owns its own draft lifecycle — BlindShotEntry clears its draft the
   * moment a stone is accepted — must leave this unset. It has no revision to be
   * identified by, and borrowing a default would give every one of its submissions the
   * same identity: the second Blind stone would then be refused as a duplicate of the
   * first, permanently, as soon as one write failed and left that first operation
   * outstanding.
   */
  usesSharedDraft?: boolean;
};

/**
 * What the athlete has typed but not yet successfully recorded.
 *
 * Owned by the parent rather than by this component, because it must outlive this
 * component's mounting: navigating to Analyze and back unmounts the Train view, and a
 * draft that lived here would be gone on return with no discard decision. The parent
 * also binds it to the exercise it was typed for, so it can never reappear in the next
 * one (see TrackerApp's manual-entry draft).
 */
export type ShotEntryDraft = {
  time: string;
  speed: string;
  /**
   * The rest of the recording intent. A stone is not only its numbers: recording a
   * retained value against the wrong handle or shot type after a remount is the same
   * class of error as recording it against the wrong exercise.
   */
  handle: Handle;
  shotType: ShotType;
  /** Only meaningful while the block's target is editable (Coach / Manual). */
  targetOverride: string;
};

export const EMPTY_SHOT_ENTRY_DRAFT: ShotEntryDraft = {
  time: "",
  speed: "",
  handle: "in",
  shotType: "draw",
  targetOverride: "",
};


type ShotEntryProps = {
  /** House supports manual Fixed and Variable Weight; active Auto Capture keeps a subordinate manual fallback. */
  appearance?: "classic" | "house";
  onAddShot: (input: AddShotInput) => boolean;
  /** The current draft for THIS exercise, held by the parent. */
  draft: ShotEntryDraft;
  /** Every call is an athlete EDIT; the parent gives it a new draft revision. */
  onChangeDraft: (draft: ShotEntryDraft) => void;
  /** The time target for the next stone. Absent when the block measures no time. */
  target: ShotEntryTarget | null;
  /** What this block measures, and the targets each measurement is judged against. */
  measurement: ResolvedBlockMeasurement;
  /**
   * "hero" (default) when this is the active capture task; "primary" when
   * Auto Capture is running and this becomes the secondary/fallback entry
   * path — see TrackerApp.tsx's Active Training surface hierarchy.
   */
  level?: "hero" | "primary";
  /**
   * False while the Session cannot accept a new stone — today that is a terminal
   * Session transition (archive-and-replace) being persisted. The typed value is kept
   * so the athlete's input survives and can simply be submitted again once the
   * transition finishes; nothing entered is discarded.
   */
  disabled?: boolean;
  /**
   * A refusal from the recording boundary, rendered where the athlete is looking.
   * Never shown as success — see the save/acknowledge rule in the specification.
   */
  errorMessage?: string | null;
};

export default function ShotEntry({
  appearance = "classic",
  onAddShot,
  draft,
  onChangeDraft,
  target,
  measurement,
  level = "hero",
  disabled = false,
  errorMessage = null,
}: ShotEntryProps) {
  const measuresTime = measurement.quantities.includes("time");
  const measuresSpeed = measurement.quantities.includes("speed");
  const measuresBoth = measuresTime && measuresSpeed;

  // EVERY part of the recording intent comes from the parent-owned draft. Keeping
  // handle, shot type or the editable target in local state would lose them the
  // moment this control unmounts — switching entry mode is enough — and a retained
  // measurement would then be recorded against the wrong handle.
  const timeInput = draft.time;
  const speedInput = draft.speed;
  const handle = draft.handle;
  const shotType = draft.shotType;
  const manualTargetInput = draft.targetOverride;

  const setTimeInput = (value: string) => onChangeDraft({ ...draft, time: value });
  const setSpeedInput = (value: string) => onChangeDraft({ ...draft, speed: value });
  const setHandle = (value: Handle) => onChangeDraft({ ...draft, handle: value });
  const setShotType = (value: ShotType) =>
    onChangeDraft({ ...draft, shotType: value });
  const setManualTargetInput = (value: string) =>
    onChangeDraft({ ...draft, targetOverride: value });

  const [localError, setLocalError] = useState<string | null>(null);

  // There is deliberately NO resync of an in-progress draft here.
  //
  // This control used to re-apply the expected handle and the generated target
  // whenever the parent recomputed them, during render. Both are derived from the
  // stones recorded so far, so an unrelated stone arriving from a device — on the
  // shared capture queue, while the athlete was midway through typing — silently
  // rewrote the handle of a draft that had already been started. A stone begun as In
  // was then recorded as Out. It also wrote to parent state during a child render,
  // which React rightly warns about.
  //
  // Defaults belong to a draft's BIRTH, not to its lifetime. The parent seeds them (see
  // `manualEntryDraftForOwner`) both for a genuinely new draft and for one whose values
  // have been submitted and not yet touched — which is what keeps automatic handle
  // progression working for a stone started before the previous write acknowledges.
  // Until the athlete edits it, a started draft keeps the whole intent it was started
  // with; once they choose a handle or shot type for the next stone, that choice is
  // theirs and nothing re-applies a default over it.

  function handleSaveShot() {
    // The same gate the button carries, applied to EVERY submission path — pressing
    // Enter must not reach a mutation the control is visibly refusing.
    if (disabled) return;

    // Blank means MISSING, which a Both stone may legitimately be on one side. A
    // non-blank field that does not parse is an ERROR, not a missing value: silently
    // dropping it would save a stone the athlete believes carries two measurements.
    const timeTyped = timeInput.trim() !== "";
    const speedTyped = speedInput.trim() !== "";

    const parsedTime = measuresTime && timeTyped ? parseReleaseTime(timeInput) : null;
    const parsedSpeed =
      measuresSpeed && speedTyped ? parseSpeedInput(speedInput) : null;

    if (measuresTime && timeTyped && (parsedTime === null || parsedTime <= 0)) {
      setLocalError("Enter a release time greater than zero, or leave it empty.");
      return;
    }

    if (measuresSpeed && speedTyped && parsedSpeed === null) {
      setLocalError("Enter a speed in m/s greater than zero, or leave it empty.");
      return;
    }

    if (parsedTime === null && parsedSpeed === null) {
      setLocalError(
        measuresBoth
          ? "Enter a release time, a speed, or both."
          : measuresSpeed
            ? "Enter a speed in m/s."
            : "Enter a release time."
      );
      return;
    }

    // No measurement-mode-specific range is enforced here on purpose — there's no
    // validated Hog-Hog target range in this project (see variableTargets.ts), so
    // Manual mode only checks that the value is a usable positive number, not a
    // sport-specific bound.
    const parsedTarget =
      target?.editable && parsedTime !== null
        ? parseReleaseTime(manualTargetInput)
        : null;

    if (
      target?.editable &&
      parsedTime !== null &&
      (parsedTarget === null || parsedTarget <= 0)
    ) {
      setLocalError("Enter a valid target time.");
      return;
    }

    setLocalError(null);

    // Idempotency is the PARENT's job (see TrackerApp's draft revision). A guard kept
    // here could not survive this control unmounting, which is exactly when a
    // duplicate becomes possible.
    //
    // The parent is the only thing that knows whether a stone can be recorded right
    // now — it may refuse, for example while a terminal Session transition is being
    // written. It is ALSO the only thing that knows whether the stone was durably
    // written, so clearing the draft is its decision, not this control's: input
    // cleared here would vanish on a storage failure the athlete never saw.
    onAddShot({
      ...(parsedTime !== null ? { releaseTime: parsedTime } : {}),
      ...(parsedSpeed !== null ? { speed: parsedSpeed } : {}),
      handle,
      shotType,
      ...(parsedTarget !== null ? { targetTimeOverride: parsedTarget } : {}),
      usesSharedDraft: true,
    });
  }

  const shownError = localError ?? errorMessage;

  // Presentation only: both layouts submit through the same validation and
  // parent-owned draft/acknowledgement boundary above. During Auto Capture the
  // manual fallback keeps its subordinate classic surface.
  if (appearance === "house" && level === "hero") {
    return (
      <div className="space-y-4" data-testid="house-shot-entry">
        <h2 className="text-xs font-medium text-[var(--house-muted)]">Add Shot</h2>
        <div className="house-hero">
          <div className="mb-4 flex items-center justify-between gap-3">
            <span className="house-hero-muted text-xs">{measuresBoth ? "Time + Speed" : measuresSpeed ? "Your speed" : "Your release time"}</span>
            <span className="house-hero-muted text-xs">Manual entry</span>
          </div>
          <div className={`house-measurements ${measuresBoth ? "house-measurements-both" : ""}`}>
            {measurement.quantities.map((quantity) => {
              const isTime = quantity === "time";
              const id = isTime ? "shot-entry-release-time" : "shot-entry-speed";
              return (
                <div key={quantity} className="house-measurement">
                  <label htmlFor={id}>
                    {isTime ? "Release Time (s)" : "Speed (m/s)"}{measuresBoth && " — optional"}
                  </label>
                  <div className="house-number-row">
                    <input
                      id={id}
                      type="text"
                      inputMode="decimal"
                      enterKeyHint="done"
                      autoComplete="off"
                      placeholder={isTime ? "3.75 or 375" : "—"}
                      value={isTime ? timeInput : speedInput}
                      aria-invalid={shownError ? true : undefined}
                      aria-describedby={shownError ? "house-shot-error" : undefined}
                      onKeyDown={(event) => {
                        if (event.key === "Enter") {
                          event.preventDefault();
                          handleSaveShot();
                        }
                      }}
                      onChange={(event) => {
                        const value = event.target.value;
                        if (isTime ? /^[0-9.,]*$/.test(value) : SPEED_INPUT_PATTERN.test(value)) {
                          if (isTime) setTimeInput(value);
                          else setSpeedInput(value);
                        }
                      }}
                      className="house-number"
                    />
                    <span aria-hidden="true" className="house-unit">{isTime ? "s" : "m/s"}</span>
                  </div>
                </div>
              );
            })}
          </div>
        </div>
        <div className="house-targets" aria-label="Targets for Next Shot">
          {measurement.quantities.map((quantity) => {
            const config = measurement[quantity];
            if (!config) return null;
            const isTime = quantity === "time";
            return (
              <div key={quantity} className="house-target-row">
                <div>
                  <p className="text-sm font-medium">{isTime ? "Target time" : "Target speed"}</p>
                  <small>On Target {toleranceBandLabel(config.tolerance.onTarget, quantity)}</small>
                </div>
                {isTime && target?.editable ? (
                  <input aria-label="Target Time" type="text" inputMode="decimal" value={manualTargetInput}
                    onChange={(event) => { if (/^[0-9.,]*$/.test(event.target.value)) setManualTargetInput(event.target.value); }}
                    className="min-h-11 w-28 rounded-xl border border-slate-300 bg-white px-3 text-lg" />
                ) : (
                  <strong>{isTime ? formatReleaseTime(target?.value ?? config.target) : formatSpeed(config.target)}</strong>
                )}
              </div>
            );
          })}
        </div>
        {measuresBoth && <p className="text-xs text-[var(--house-muted)]">Enter either measurement or both. Add a missing measurement to the saved stone later.</p>}
        <div role="group" aria-label="Handle" className="grid grid-cols-2 gap-2">
          {(["in", "out"] as Handle[]).map((value) => (
            <button key={value} type="button" aria-pressed={handle === value} onClick={() => setHandle(value)} className="house-select">
              {value === "in" ? "In Handle" : "Out Handle"}
            </button>
          ))}
        </div>
        <div role="group" aria-label="Shot type" className="grid grid-cols-2 gap-2">
          {(["draw", "takeout"] as ShotType[]).map((value) => (
            <button key={value} type="button" aria-pressed={shotType === value} onClick={() => setShotType(value)} className="house-select capitalize">{value}</button>
          ))}
        </div>
        {shownError && <p id="house-shot-error" role="alert" className="rounded-xl bg-red-50 p-3 text-sm text-red-800">{shownError}</p>}
        <button type="button" onClick={handleSaveShot} disabled={disabled} className="house-action">Save Shot</button>
      </div>
    );
  }

  return (
    <div className={surfaceClass(level)}>
      <h2 className="text-xl font-semibold text-slate-900">Add Shot</h2>

      {/* One compact area carrying the targets this stone is judged against, so the
          athlete never has to look elsewhere to know what they are aiming at. */}
      <div className={surfaceClass("inset", "mt-4")}>
        <div className="flex items-center justify-between gap-3">
          <p className="text-sm font-medium text-slate-700">
            {measuresBoth ? "Targets for Next Shot" : "Target for Next Shot"}
          </p>

          {target?.autoGenerated && (
            <span className="rounded-full bg-slate-900 px-2 py-1 text-xs font-medium text-white">
              Auto
            </span>
          )}
        </div>

        {measuresTime && target && (
          <>
            {target.editable ? (
              <input
                type="text"
                inputMode="decimal"
                aria-label="Target Time"
                value={manualTargetInput}
                onChange={(event) => {
                  const value = event.target.value;
                  if (/^[0-9.,]*$/.test(value)) setManualTargetInput(value);
                }}
                className="mt-2 min-h-11 w-full rounded-xl border border-slate-300 bg-white px-4 py-3 text-lg text-slate-900 placeholder:text-slate-400"
              />
            ) : (
              <p className="mt-1 text-3xl font-semibold text-slate-900">
                {formatReleaseTime(target.value)}
              </p>
            )}
          </>
        )}

        {measuresSpeed && measurement.speed && (
          <p
            className={`${measuresTime ? "mt-2 text-xl" : "mt-1 text-3xl"} font-semibold text-slate-900`}
          >
            {formatSpeed(measurement.speed.target)}
          </p>
        )}

        <p className="mt-2 text-xs text-slate-500">
          {target?.editable
            ? "Coach target — edit before saving this shot."
            : target?.autoGenerated
              ? "Generated automatically for this shot."
              : "Default target for this training block."}
        </p>
      </div>

      {measuresTime && (
        <div className="mt-4">
          <label
            className="text-xs font-medium text-slate-500"
            htmlFor="shot-entry-release-time"
          >
            Release Time (s){measuresBoth && " — optional"}
          </label>
          <input
            id="shot-entry-release-time"
            type="text"
            inputMode="decimal"
            enterKeyHint="done"
            placeholder="3.75 or 375"
            value={timeInput}
            onKeyDown={(event) => {
              if (event.key === "Enter") {
                event.preventDefault();
                handleSaveShot();
              }
            }}
            onChange={(event) => {
              const value = event.target.value;
              if (/^[0-9.,]*$/.test(value)) setTimeInput(value);
            }}
            className="mt-1 min-h-11 w-full rounded-xl border border-slate-300 bg-white px-4 py-3 text-lg text-slate-900 placeholder:text-slate-400"
          />
        </div>
      )}

      {measuresSpeed && (
        <div className="mt-4">
          <label
            className="text-xs font-medium text-slate-500"
            htmlFor="shot-entry-speed"
          >
            Speed (m/s){measuresBoth && " — optional"}
          </label>
          <input
            id="shot-entry-speed"
            type="text"
            inputMode="decimal"
            enterKeyHint="done"
            // No hundredths shorthand here: "240" is 240 m/s and is rejected as a
            // measurement, never silently rescaled to 2.40 (see speedInput.ts).
            placeholder="2.40"
            value={speedInput}
            onKeyDown={(event) => {
              if (event.key === "Enter") {
                event.preventDefault();
                handleSaveShot();
              }
            }}
            onChange={(event) => {
              const value = event.target.value;
              if (SPEED_INPUT_PATTERN.test(value)) setSpeedInput(value);
            }}
            className="mt-1 min-h-11 w-full rounded-xl border border-slate-300 bg-white px-4 py-3 text-lg text-slate-900 placeholder:text-slate-400"
          />
        </div>
      )}

      {measuresBoth && (
        <p className="mt-2 text-xs text-slate-500">
          Leave one empty to record only the other. You can add the missing one to
          this stone later.
        </p>
      )}

      <div className="mt-4 flex gap-2">
        <button
          type="button"
          onClick={() => setHandle("in")}
          className={`min-h-11 flex-1 rounded-xl px-4 py-3 font-medium transition ${
            handle === "in"
              ? "bg-slate-900 text-white"
              : "bg-slate-200 text-slate-700"
          }`}
        >
          In Handle
        </button>

        <button
          type="button"
          onClick={() => setHandle("out")}
          className={`min-h-11 flex-1 rounded-xl px-4 py-3 font-medium transition ${
            handle === "out"
              ? "bg-slate-900 text-white"
              : "bg-slate-200 text-slate-700"
          }`}
        >
          Out Handle
        </button>
      </div>

      <div className="mt-4 grid grid-cols-2 gap-2">
        {(["draw", "takeout"] as ShotType[]).map((type) => (
          <button
            key={type}
            type="button"
            onClick={() => setShotType(type)}
            className={`min-h-11 rounded-xl px-4 py-3 font-medium capitalize transition ${
              shotType === type
                ? "bg-slate-900 text-white"
                : "bg-slate-200 text-slate-700"
            }`}
          >
            {type}
          </button>
        ))}
      </div>

      {shownError && (
        <p role="alert" className="mt-3 text-sm text-red-600">
          {shownError}
        </p>
      )}

      <button
        type="button"
        onClick={handleSaveShot}
        disabled={disabled}
        className="mt-4 min-h-11 w-full rounded-xl bg-slate-900 px-4 py-3 text-white transition hover:bg-slate-700 disabled:cursor-not-allowed disabled:opacity-50"
      >
        Save Shot
      </button>
    </div>
  );
}
